//go:build ignore

// Regenerate the checked-in catalog from the Unicode specification and verify
// every image identifier against the pinned Twemoji release tree.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"io"
	"net/http"
	"os"
	"sort"
	"strconv"
	"strings"
	"time"
)

const unicodeVersion = "17.0"
const artworkVersion = "17.0.3"

func download(url string) []byte {
	client := &http.Client{Timeout: 30 * time.Second}
	request, err := http.NewRequest("GET", url, nil)
	if err != nil {
		panic(err)
	}
	request.Header.Set("User-Agent", "Sophus-emoji-catalog-generator")
	response, err := client.Do(request)
	if err != nil {
		panic(err)
	}
	defer response.Body.Close()
	if response.StatusCode != 200 {
		panic(fmt.Sprintf("catalog source returned HTTP %d: %s", response.StatusCode, url))
	}
	data, err := io.ReadAll(io.LimitReader(response.Body, 8<<20))
	if err != nil {
		panic(err)
	}
	return data
}

func main() {
	testData := download("https://unicode.org/Public/17.0.0/emoji/emoji-test.txt")
	var tree struct {
		Truncated bool `json:"truncated"`
		Tree      []struct {
			Path string `json:"path"`
		} `json:"tree"`
	}
	if err := json.Unmarshal(download("https://api.github.com/repos/jdecked/twemoji/git/trees/v"+artworkVersion+"?recursive=1"), &tree); err != nil {
		panic(err)
	}
	if tree.Truncated {
		panic("artwork tree truncated")
	}
	available := make(map[string]bool)
	normalized := make(map[string]string)
	for _, item := range tree.Tree {
		if strings.HasPrefix(item.Path, "assets/72x72/") && strings.HasSuffix(item.Path, ".png") {
			key := strings.TrimSuffix(strings.TrimPrefix(item.Path, "assets/72x72/"), ".png")
			available[key] = true
			withoutVariation := strings.ReplaceAll(key, "-fe0f", "")
			if previous, ok := normalized[withoutVariation]; !ok || key < previous {
				normalized[withoutVariation] = key
			}
		}
	}
	images := make(map[string]string)
	fullyQualified := 0
	for _, line := range strings.Split(string(testData), "\n") {
		line = strings.TrimSpace(strings.SplitN(line, "#", 2)[0])
		if line == "" {
			continue
		}
		parts := strings.SplitN(line, ";", 2)
		if len(parts) != 2 {
			panic("malformed emoji catalog")
		}
		if strings.TrimSpace(parts[1]) == "fully-qualified" {
			fullyQualified++
		}
		var sequence []rune
		var codes, withoutVariation []string
		for _, field := range strings.Fields(parts[0]) {
			code, err := strconv.ParseInt(field, 16, 32)
			if err != nil {
				panic(err)
			}
			sequence = append(sequence, rune(code))
			value := fmt.Sprintf("%x", code)
			codes = append(codes, value)
			if code != 0xfe0f {
				withoutVariation = append(withoutVariation, value)
			}
		}
		key := strings.Join(codes, "-")
		if !available[key] {
			key = strings.Join(withoutVariation, "-")
		}
		if !available[key] {
			if canonical, ok := normalized[key]; ok {
				key = canonical
			}
		}
		if !available[key] {
			panic("emoji artwork missing for: " + parts[0])
		}
		images[string(sequence)] = key
	}
	if fullyQualified < 3900 {
		panic("incomplete Unicode catalog")
	}
	var output bytes.Buffer
	fmt.Fprintln(&output, "// Code generated by go generate; DO NOT EDIT.")
	fmt.Fprintln(&output, "// Source: Unicode emoji-test.txt (Unicode data license), Twemoji (CC BY 4.0).")
	fmt.Fprintln(&output, "package emojis")
	fmt.Fprintf(&output, "const UnicodeVersion = %q\nconst ArtworkVersion = %q\nconst FullyQualifiedCount = %d\n", unicodeVersion, artworkVersion, fullyQualified)
	fmt.Fprintln(&output, "var emojiImages = map[string]string{")
	keys := make([]string, 0, len(images))
	for key := range images {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	for _, key := range keys {
		fmt.Fprintf(&output, "%q: %q,\n", key, images[key])
	}
	fmt.Fprintln(&output, "}")
	formatted, err := format.Source(output.Bytes())
	if err != nil {
		panic(err)
	}
	if err := os.WriteFile("catalog_data.go", formatted, 0644); err != nil {
		panic(err)
	}
	fmt.Printf("Verified %d fully-qualified emojis and %d standardized variants against %d Twemoji images.\n", fullyQualified, len(images), len(available))
}
