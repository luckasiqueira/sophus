// Package monitor samples this server's resource consumption and activity
// (agents online, connected instances) for the super-admin dashboard.
package monitor

import (
	"bufio"
	"context"
	"log"
	"os"
	"runtime"
	"sort"
	"strconv"
	"strings"
	"sync"
	"sync/atomic"
	"time"

	"sophus/internal/repo"
	"sophus/pkg/http/middlewares"
)

const (
	sampleInterval = 2 * time.Second
	sampleHistory  = 900 // 30 minutes at the sample interval
	// Database-server statistics and instance counts are refreshed every
	// fifth sample: they query PostgreSQL, unlike the in-process readings.
	slowEvery = 5
)

type Sample struct {
	Time                time.Time `json:"t"`
	CPUPercent          float64   `json:"cpu"`
	SystemCPUPercent    float64   `json:"systemCpu"`
	Goroutines          int       `json:"goroutines"`
	HeapMB              float64   `json:"heapMB"`
	RuntimeMB           float64   `json:"runtimeMB"`
	RSSMB               float64   `json:"rssMB"`
	SystemMemoryPercent float64   `json:"systemMemoryPercent"`
	Load1               float64   `json:"load1"`
	GCPauseMs           float64   `json:"gcPauseMs"`
	DBOpen              int       `json:"dbOpen"`
	DBInUse             int       `json:"dbInUse"`
	DBWaitMs            float64   `json:"dbWaitMs"`
	PGConnections       int       `json:"pgConnections"`
	DatabaseMB          float64   `json:"databaseMB"`
	// Activity on the platform.
	AgentsOnline                int `json:"agentsOnline"`
	SimulatedAgentsOnline       int `json:"simulatedAgentsOnline"`
	SSEConnections              int `json:"sseConnections"`
	InstancesConnected          int `json:"instancesConnected"`
	SimulatedInstancesConnected int `json:"simulatedInstancesConnected"`
	// Traffic generated by the stress-test simulator.
	RequestsPerSecond  float64 `json:"requestsPerSecond"`
	AvgLatencyMs       float64 `json:"avgLatencyMs"`
	P95LatencyMs       float64 `json:"p95LatencyMs"`
	ErrorsPerSecond    float64 `json:"errorsPerSecond"`
	WebhooksPerSecond  float64 `json:"webhooksPerSecond"`
	SimulatorSSEOpen   int64   `json:"simulatorSseOpen"`
	SSEEventsPerSecond float64 `json:"sseEventsPerSecond"`
}

type Host struct {
	CPUs          int       `json:"cpus"`
	GOMAXPROCS    int       `json:"gomaxprocs"`
	OS            string    `json:"os"`
	SystemMemory  float64   `json:"systemMemoryMB"`
	ProcSupported bool      `json:"procSupported"`
	StartedAt     time.Time `json:"startedAt"`
}

// Traffic aggregates simulator requests between two samples.
type Traffic struct {
	requests, errors, webhooks, sseEvents atomic.Int64
	SSEOpen                               atomic.Int64
	mu                                    sync.Mutex
	latencies                             []float64
}

// Simulator collects the stress-test simulator's own requests.
var Simulator = &Traffic{}

func (t *Traffic) Record(duration time.Duration, failed bool) {
	t.requests.Add(1)
	if failed {
		t.errors.Add(1)
	}
	t.mu.Lock()
	if len(t.latencies) < 20000 {
		t.latencies = append(t.latencies, float64(duration.Microseconds())/1000)
	}
	t.mu.Unlock()
}

func (t *Traffic) Webhook()  { t.webhooks.Add(1) }
func (t *Traffic) SSEEvent() { t.sseEvents.Add(1) }

func (t *Traffic) drain() (requests, errors, webhooks, events int64, latencies []float64) {
	t.mu.Lock()
	latencies, t.latencies = t.latencies, nil
	t.mu.Unlock()
	return t.requests.Swap(0), t.errors.Swap(0), t.webhooks.Swap(0), t.sseEvents.Swap(0), latencies
}

var sampler = struct {
	sync.Mutex
	started    time.Time
	samples    []Sample
	lastCPU    time.Duration
	lastSystem cpuTimes
	lastAt     time.Time
	lastGC     uint32
	lastWait   time.Duration
	ticks      int
	slow       Sample // last database-backed readings, reused between refreshes
}{}

// Start samples every two seconds until ctx ends, keeping 30 minutes of
// history so the dashboard opens with recent data.
func Start(ctx context.Context) {
	sampler.Lock()
	if !sampler.started.IsZero() {
		sampler.Unlock()
		return
	}
	sampler.started = time.Now()
	sampler.Unlock()
	resetBaseline()
	go func() {
		ticker := time.NewTicker(sampleInterval)
		defer ticker.Stop()
		for {
			select {
			case <-ctx.Done():
				return
			case <-ticker.C:
				takeSample()
			}
		}
	}()
}

func resetBaseline() {
	cpu, _ := processCPUTime()
	var stats runtime.MemStats
	runtime.ReadMemStats(&stats)
	sampler.Lock()
	sampler.lastCPU = cpu
	sampler.lastSystem, _ = readSystemCPU()
	sampler.lastAt = time.Now()
	sampler.lastGC = stats.NumGC
	sampler.lastWait = repo.GetDatabaseStats(false).WaitDuration
	sampler.Unlock()
	Simulator.drain()
}

func takeSample() {
	now := time.Now()
	sample := Sample{Time: now, Goroutines: runtime.NumGoroutine(), SimulatorSSEOpen: Simulator.SSEOpen.Load(),
		SSEConnections: middlewares.OpenSSEConnections()}
	var stats runtime.MemStats
	runtime.ReadMemStats(&stats)
	sample.HeapMB = megabytes(stats.HeapAlloc)
	sample.RuntimeMB = megabytes(stats.Sys)
	online := middlewares.OnlineAgentIDs()
	var err error
	if sample.AgentsOnline, sample.SimulatedAgentsOnline, err = repo.CountOnlineAgents(online); err != nil {
		log.Printf("monitor: online agents failed: %v", err)
	}

	sampler.Lock()
	elapsed := now.Sub(sampler.lastAt).Seconds()
	if cpu, ok := processCPUTime(); ok && elapsed > 0 {
		// Share of the whole machine, so 100% means every core is busy.
		sample.CPUPercent = (cpu - sampler.lastCPU).Seconds() / elapsed / float64(runtime.NumCPU()) * 100
		sampler.lastCPU = cpu
	}
	if system, ok := readSystemCPU(); ok {
		sample.SystemCPUPercent = system.busyPercent(sampler.lastSystem)
		sampler.lastSystem = system
	}
	for index := sampler.lastGC; index < stats.NumGC && index < sampler.lastGC+256; index++ {
		sample.GCPauseMs += float64(stats.PauseNs[index%256]) / 1e6
	}
	sampler.lastGC = stats.NumGC
	slow := sampler.ticks%slowEvery == 0
	database := repo.GetDatabaseStats(slow)
	if slow {
		sampler.slow.PGConnections = database.ServerConnections
		sampler.slow.DatabaseMB = float64(database.DatabaseBytes) / (1 << 20)
		if real, simulated, err := repo.CountConnectedInstances(); err == nil {
			sampler.slow.InstancesConnected, sampler.slow.SimulatedInstancesConnected = real, simulated
		} else {
			log.Printf("monitor: connected instances failed: %v", err)
		}
	}
	sample.DBOpen, sample.DBInUse = database.OpenConnections, database.InUse
	sample.DBWaitMs = float64((database.WaitDuration - sampler.lastWait).Microseconds()) / 1000
	sampler.lastWait = database.WaitDuration
	sample.PGConnections, sample.DatabaseMB = sampler.slow.PGConnections, sampler.slow.DatabaseMB
	sample.InstancesConnected, sample.SimulatedInstancesConnected = sampler.slow.InstancesConnected, sampler.slow.SimulatedInstancesConnected
	sampler.ticks++
	sampler.lastAt = now
	sampler.Unlock()

	sample.RSSMB = readRSSMB()
	sample.SystemMemoryPercent, _ = readSystemMemory()
	sample.Load1 = readLoad1()
	requests, errors, webhooks, events, latencies := Simulator.drain()
	if elapsed > 0 {
		sample.RequestsPerSecond = float64(requests) / elapsed
		sample.ErrorsPerSecond = float64(errors) / elapsed
		sample.WebhooksPerSecond = float64(webhooks) / elapsed
		sample.SSEEventsPerSecond = float64(events) / elapsed
	}
	sample.AvgLatencyMs, sample.P95LatencyMs = latencyStats(latencies)

	sampler.Lock()
	sampler.samples = append(sampler.samples, sample)
	if len(sampler.samples) > sampleHistory {
		sampler.samples = append([]Sample(nil), sampler.samples[len(sampler.samples)-sampleHistory:]...)
	}
	sampler.Unlock()
}

func latencyStats(latencies []float64) (average, p95 float64) {
	if len(latencies) == 0 {
		return 0, 0
	}
	sort.Float64s(latencies)
	total := 0.0
	for _, value := range latencies {
		total += value
	}
	return total / float64(len(latencies)), latencies[min(len(latencies)-1, len(latencies)*95/100)]
}

// Samples returns the history recorded after the given time (zero for all).
func Samples(since time.Time) []Sample {
	sampler.Lock()
	defer sampler.Unlock()
	result := []Sample{}
	for _, sample := range sampler.samples {
		if sample.Time.After(since) {
			result = append(result, sample)
		}
	}
	return result
}

func HostInfo() Host {
	_, total := readSystemMemory()
	_, procSupported := readSystemCPU()
	sampler.Lock()
	started := sampler.started
	sampler.Unlock()
	return Host{CPUs: runtime.NumCPU(), GOMAXPROCS: runtime.GOMAXPROCS(0), OS: runtime.GOOS + "/" + runtime.GOARCH,
		SystemMemory: total, ProcSupported: procSupported, StartedAt: started}
}

func megabytes(value uint64) float64 {
	return float64(value) / (1 << 20)
}

// The readers below use Linux /proc and report zero elsewhere, where only the
// process-level metrics are available.
type cpuTimes struct{ idle, total uint64 }

func (current cpuTimes) busyPercent(previous cpuTimes) float64 {
	total := float64(current.total - previous.total)
	if total <= 0 || current.total < previous.total {
		return 0
	}
	return (total - float64(current.idle-previous.idle)) / total * 100
}

func readSystemCPU() (cpuTimes, bool) {
	file, err := os.Open("/proc/stat")
	if err != nil {
		return cpuTimes{}, false
	}
	defer file.Close()
	scanner := bufio.NewScanner(file)
	if !scanner.Scan() {
		return cpuTimes{}, false
	}
	fields := strings.Fields(scanner.Text())
	if len(fields) < 5 || fields[0] != "cpu" {
		return cpuTimes{}, false
	}
	var times cpuTimes
	for index, field := range fields[1:] {
		value, _ := strconv.ParseUint(field, 10, 64)
		times.total += value
		if index == 3 || index == 4 { // idle, iowait
			times.idle += value
		}
	}
	return times, true
}

func readRSSMB() float64 {
	return procValueKB("/proc/self/status", "VmRSS:") / 1024
}

func readSystemMemory() (usedPercent, totalMB float64) {
	total := procValueKB("/proc/meminfo", "MemTotal:")
	available := procValueKB("/proc/meminfo", "MemAvailable:")
	if total <= 0 {
		return 0, 0
	}
	return (total - available) / total * 100, total / 1024
}

func readLoad1() float64 {
	data, err := os.ReadFile("/proc/loadavg")
	if err != nil {
		return 0
	}
	fields := strings.Fields(string(data))
	if len(fields) == 0 {
		return 0
	}
	value, _ := strconv.ParseFloat(fields[0], 64)
	return value
}

func procValueKB(path, key string) float64 {
	file, err := os.Open(path)
	if err != nil {
		return 0
	}
	defer file.Close()
	scanner := bufio.NewScanner(file)
	for scanner.Scan() {
		line := scanner.Text()
		if strings.HasPrefix(line, key) {
			fields := strings.Fields(strings.TrimPrefix(line, key))
			if len(fields) > 0 {
				value, _ := strconv.ParseFloat(fields[0], 64)
				return value
			}
		}
	}
	return 0
}
