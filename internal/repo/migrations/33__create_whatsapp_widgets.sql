CREATE TABLE public.whatsapp_widgets (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "companyId" integer NOT NULL REFERENCES public.companies(id) ON UPDATE CASCADE ON DELETE CASCADE,
    "publicId" uuid NOT NULL,
    name character varying(80) NOT NULL,
    "phoneNumber" character varying(15) NOT NULL,
    "callToAction" character varying(80) NOT NULL,
    color character varying(7) NOT NULL,
    "isActive" boolean NOT NULL DEFAULT true,
    revision integer NOT NULL DEFAULT 1,
    "createdAt" timestamp with time zone NOT NULL DEFAULT now(),
    "updatedAt" timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT whatsapp_widgets_public_id_unique UNIQUE ("publicId"),
    CONSTRAINT whatsapp_widgets_phone_check CHECK ("phoneNumber" ~ '^[0-9]{8,15}$'),
    CONSTRAINT whatsapp_widgets_color_check CHECK (color ~ '^#[0-9A-Fa-f]{6}$'),
    CONSTRAINT whatsapp_widgets_revision_check CHECK (revision > 0)
);

