    name character varying(100) NOT NULL,
    provider character varying(20) NOT NULL,
    model character varying(120) NOT NULL,
    "apiKeyCiphertext" text NOT NULL,
    "systemPrompt" text NOT NULL DEFAULT '',
    "knowledgeBase" text NOT NULL DEFAULT '',
    tone character varying(20) NOT NULL DEFAULT 'professional',
    "maxOutputTokens" integer NOT NULL DEFAULT 1024,
    temperature double precision NOT NULL DEFAULT 0.4,
    "historyLimit" integer NOT NULL DEFAULT 20,
    "welcomeMessage" text NOT NULL DEFAULT '',
