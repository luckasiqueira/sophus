CREATE TABLE public.ai_agent_sessions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "companyId" integer NOT NULL REFERENCES public.companies(id) ON UPDATE CASCADE ON DELETE CASCADE,
    "conversationId" integer NOT NULL REFERENCES public.conversations(id) ON UPDATE CASCADE ON DELETE CASCADE,
    "aiAgentId" integer NOT NULL REFERENCES public.ai_agents(id) ON UPDATE CASCADE ON DELETE CASCADE,
    status character varying(20) NOT NULL DEFAULT 'active',
    "startedAt" timestamp with time zone NOT NULL DEFAULT now(),
    "updatedAt" timestamp with time zone NOT NULL DEFAULT now(),
    "endedAt" timestamp with time zone,
    CONSTRAINT ai_agent_sessions_status_check CHECK (status IN ('active', 'ended', 'failed')),
    CONSTRAINT ai_agent_sessions_conversation_unique UNIQUE ("conversationId")
);

CREATE INDEX ai_agent_sessions_active_idx ON public.ai_agent_sessions ("companyId", "conversationId") WHERE status = 'active';

