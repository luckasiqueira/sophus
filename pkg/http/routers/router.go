package routers

import (
	"net/http"
	"sophus/logos"
	"sophus/pkg/http/controllers"
	"sophus/pkg/http/middlewares"
	"sophus/utils/env"
	"time"

	"github.com/kataras/iris/v12"
)

func Router(r *iris.Application) {
	r.Use(middlewares.SecurityHeaders)
	brandAssets := iris.FromStd(http.StripPrefix("/logos/", http.FileServer(http.FS(logos.Files))))
	r.Get("/logos/{file:string}", brandAssets)
	r.Head("/logos/{file:string}", brandAssets)
	r.Get("/login", controllers.Login)
	r.Get("/support/return", middlewares.AuthPlatform, controllers.SupportReturnPage)
	r.Get("/login/2fa", controllers.PlatformSecondFactorPage)
	r.Post("/login/2fa", middlewares.IPRateLimit(20, 5*time.Minute), middlewares.LimitRequestBody(1<<20), middlewares.RequireSameOrigin, controllers.VerifyPlatformSecondFactor)
	r.Post("/dologin", middlewares.IPRateLimit(10, 5*time.Minute), middlewares.LimitRequestBody(1<<20), middlewares.RequireSameOrigin, controllers.DoLogin)
	r.Get("/setup", controllers.SaaSSetupPage)
	r.Post("/setup", middlewares.IPRateLimit(10, 10*time.Minute), middlewares.LimitRequestBody(1<<20), middlewares.RequireSameOrigin, controllers.CreateSaaSSetup)
	r.Get("/billing", controllers.BillingPage)
	r.Get("/billing/api/catalog", controllers.PublicBillingCatalog)
	r.Post("/billing/api/register", middlewares.IPRateLimit(5, time.Hour), middlewares.LimitRequestBody(1<<20), middlewares.RequireSameOrigin, middlewares.RequireStructuredContentType, controllers.RegisterCompanyTrial)
	r.Post("/logout", middlewares.RequireSameOrigin, controllers.Logout)

	r.Post("/webhook/{webhookId:uuid}", middlewares.RequireStructuredContentType, middlewares.AuthWebhook, controllers.Webhook)
	r.Post("/payments/mercado-pago/webhook", middlewares.IPRateLimit(60, time.Minute), middlewares.RequireStructuredContentType, controllers.MercadoPagoWebhook)
	r.Post("/payments/abacatepay/webhook", middlewares.IPRateLimit(60, time.Minute), middlewares.RequireStructuredContentType, controllers.AbacatePayWebhook)
	r.Get("/integrations/whatsapp/{publicId:uuid}/widget.js", controllers.ServeWhatsAppWidget)
	r.Get("/media-public/{companyId:int}/{scope:string}/{file:string}", controllers.ServeForwardMedia)
	r.Get("/medias/{companyId:int}/flows/{file:string}", middlewares.AuthFlowMedia, controllers.ServeFlowMedia)
	r.Get("/", middlewares.AuthUser, controllers.Home)
	r.Get("/settings", middlewares.AuthUser, controllers.SettingsPage)
	r.Get("/profile", middlewares.AuthUser, controllers.UserProfilePage)
	r.Get("/preferences", middlewares.AuthLogin, controllers.AgentPreferencesPage)
	r.Get("/companies/{id:int}", middlewares.AuthUser, controllers.CompanyOverviewPage)

	managementAPI := r.Party("/management/api")
	managementAPI.Use(middlewares.AuthUser, middlewares.LimitRequestBody(12<<20), middlewares.RequireSameOrigin, middlewares.RequireStructuredContentType)
	{
		managementAPI.Get("/overview", controllers.SaaSOverview)
		managementAPI.Post("/companies/{id:int}/support", controllers.StartCompanySupport)
		managementAPI.Post("/support/stop", controllers.StopCompanySupport)
		managementAPI.Get("/support-session", controllers.GetSupportSession)
		managementAPI.Put("/user-profile", controllers.UpdateUserProfile)
		managementAPI.Get("/preferences", controllers.GetAgentPreferences)
		managementAPI.Put("/preferences", controllers.UpdateAgentPreferences)
		managementAPI.Post("/onboarding", controllers.SaveAgentOnboarding)
		managementAPI.Get("/audit-events", controllers.ListAuditEvents)
		managementAPI.Get("/company/audit-events", controllers.ListCompanyAuditEvents)
		managementAPI.Get("/settings", controllers.GetSettings)
		managementAPI.Put("/settings", controllers.UpdateSettings)
		managementAPI.Put("/profile", controllers.UpdateSaaSProfile)
		managementAPI.Post("/plans", controllers.CreateSaaSPlan)
		managementAPI.Put("/plans/{id:int}", controllers.UpdateSaaSPlan)
		managementAPI.Put("/addon-prices", controllers.UpdateSaaSAddonPrices)
		managementAPI.Get("/companies/{id:int}/addons", controllers.ListSaaSCompanyAddons)
		managementAPI.Put("/companies/{id:int}/addons", controllers.UpdateSaaSCompanyAddons)
		managementAPI.Post("/companies", controllers.CreateSaaSCompany)
		managementAPI.Put("/companies/{id:int}", controllers.UpdateSaaSCompany)
		managementAPI.Put("/companies/{id:int}/status", controllers.SetSaaSCompanyStatus)
		managementAPI.Put("/companies/{id:int}/plan", controllers.ChangeSaaSCompanyPlan)
		managementAPI.Put("/companies/{id:int}/due-date", controllers.UpdateSaaSCompanyDueDate)
		managementAPI.Post("/companies/{id:int}/subscription/reactivate", controllers.ReactivateSaaSCompanySubscription)
		managementAPI.Post("/companies/{id:int}/subscription/redemption", controllers.GrantSaaSCompanySubscriptionRedemption)
		managementAPI.Get("/companies/{id:int}/payments", controllers.ListSaaSCompanyPayments)
		managementAPI.Get("/companies/{id:int}/credits", controllers.GetSaaSCompanyCredits)
		managementAPI.Put("/companies/{id:int}/payments/{paymentId:int}", controllers.UpdateSaaSCompanyPayment)
		managementAPI.Get("/payments", controllers.ListSaaSPayments)
		managementAPI.Get("/companies/{id:int}/overview", controllers.GetCompanyOperationalOverview)
		managementAPI.Post("/companies/{id:int}/checkout", controllers.CreateSaaSCompanyCheckout)
		managementAPI.Get("/agents", controllers.ListCompanyAgents)
		managementAPI.Post("/agents", controllers.CreateCompanyAgent)
		managementAPI.Put("/agents/{id:int}", controllers.AuditCompanyAction("update", "agent", controllers.UpdateCompanyAgent))
		managementAPI.Delete("/agents/{id:int}", controllers.AuditCompanyAction("delete", "agent", controllers.DeleteCompanyAgent))
		managementAPI.Get("/billing", controllers.GetCompanyBilling)
		managementAPI.Get("/billing/addons", controllers.ListCompanyAddons)
		managementAPI.Put("/billing/addons", controllers.UpdateCompanyAddons)
		managementAPI.Post("/billing/checkout", controllers.CreateCompanyCheckout)
		managementAPI.Put("/billing/cycle", controllers.UpdateCompanyBillingCycle)
		managementAPI.Put("/billing/plan", controllers.UpdateCompanyBillingPlan)
		managementAPI.Get("/media", controllers.ListCompanyMedia)
		managementAPI.Post("/media/cleanup", controllers.CleanupCompanyMedia)
		managementAPI.Get("/media/{scope:string}/{file:string}/download", controllers.DownloadCompanyMedia)
		managementAPI.Get("/media/{scope:string}/{file:string}/content", controllers.PreviewCompanyMedia)
		managementAPI.Post("/media/{scope:string}/{file:string}/forward", controllers.ForwardCompanyMedia)
		managementAPI.Delete("/media/{scope:string}/{file:string}", controllers.DeleteCompanyMedia)
		managementAPI.Get("/integrations/whatsapp", controllers.ListWhatsAppWidgets)
		managementAPI.Post("/integrations/whatsapp", controllers.CreateWhatsAppWidget)
		managementAPI.Put("/integrations/whatsapp/{id:int}", controllers.UpdateWhatsAppWidget)
		managementAPI.Delete("/integrations/whatsapp/{id:int}", controllers.DeleteWhatsAppWidget)
		managementAPI.Get("/conversation-picker/connections", controllers.ListContactPickerConnections)
		managementAPI.Get("/contacts", controllers.ListCompanyContacts)
		managementAPI.Get("/contact-tags", controllers.ListContactTags)
		managementAPI.Get("/quick-replies", controllers.ListQuickReplies)
		managementAPI.Post("/quick-replies", controllers.CreateQuickReply)
		managementAPI.Put("/quick-replies/{id:int}", controllers.UpdateQuickReply)
		managementAPI.Delete("/quick-replies/{id:int}", controllers.DeleteQuickReply)
		managementAPI.Post("/contact-tags", controllers.CreateContactTag)
		managementAPI.Put("/contact-tags/{id:int}", controllers.RenameContactTag)
		managementAPI.Delete("/contact-tags/{id:int}", controllers.DeleteContactTag)
		managementAPI.Get("/contacts/{id:int}/avatar", controllers.ContactAvatar)
		managementAPI.Post("/contacts/{id:int}/avatar/refresh", controllers.RefreshContactAvatar)
		managementAPI.Put("/contacts/{id:int}", controllers.AuditCompanyAction("update", "contact", controllers.UpdateCompanyContact))
		managementAPI.Delete("/contacts/{id:int}", controllers.AuditCompanyAction("delete", "contact", controllers.DeleteCompanyContact))
		managementAPI.Put("/contacts/{id:int}/tags", controllers.SetCompanyContactTags)
		managementAPI.Post("/conversations/open", controllers.OpenContactConversation)
		managementAPI.Get("/ai-credentials", controllers.ListAICredentials)
		managementAPI.Get("/ai-credentials/models", controllers.ListAICredentialModels)
		managementAPI.Post("/ai-credentials", controllers.CreateAICredential)
		managementAPI.Put("/ai-credentials/{id:int}", controllers.UpdateAICredential)
		managementAPI.Delete("/ai-credentials/{id:int}", controllers.DeleteAICredential)
		managementAPI.Post("/ai-credentials/{id:int}/test", controllers.TestAICredential)
		managementAPI.Get("/ai-agents", controllers.ListAIAgents)
		managementAPI.Get("/ai-agents/connections", controllers.ListAIAgentConnections)
		managementAPI.Get("/ai-agents/models", controllers.ListAIAgentModels)
		managementAPI.Post("/ai-agents/knowledge/pdf", controllers.ExtractAIAgentKnowledgePDF)
		managementAPI.Post("/ai-agents", controllers.CreateAIAgent)
		managementAPI.Put("/ai-agents/{id:int}", controllers.UpdateAIAgent)
		managementAPI.Delete("/ai-agents/{id:int}", controllers.DeleteAIAgent)
		managementAPI.Post("/ai-agents/{id:int}/test", controllers.TestAIAgent)
	}

	api := r.Party("/api")
	api.Use(middlewares.AuthAPI, middlewares.LimitRequestBody(2<<20), middlewares.RequireCookieSameOrigin, middlewares.RequireStructuredContentType)
	{
		message := api.Party("/message")
		{
			message.Post("/send", controllers.SendMessage)
		}
		api.Get("/departments", controllers.GetDepartmentSettings)
		api.Post("/departments", controllers.CreateDepartment)
		api.Put("/departments/{id:int}", controllers.UpdateDepartment)
		api.Delete("/departments/{id:int}", controllers.DeleteDepartment)
		api.Put("/departments/agents/{id:int}", controllers.UpdateAgentDepartments)
	}

	web := r.Party("/")
	web.Use(middlewares.AuthLogin, middlewares.LimitRequestBody(55<<20), middlewares.RequireSameOrigin)

	medias := web.Party("/medias")
	medias.Use(middlewares.AuthMediaCompany)
	medias.HandleDir("/", iris.Dir(env.Backend["MEDIA_DIRECTORY"]), iris.DirOptions{})

	web.Get("/sse", middlewares.AuthSubscription, middlewares.SSEMessages)
	web.Get("/sse/conversations", middlewares.AuthSubscription, middlewares.SSEConversations)

	web.Get("/messages", middlewares.AuthSubscription, controllers.Messages)
	web.Get("/messages/list", middlewares.AuthSubscription, controllers.ConversationList)
	web.Get("/messages/protocol", middlewares.AuthSubscription, controllers.OpenConversationProtocol)
	web.Get("/messages/{url:uuid}", middlewares.AuthSubscription, controllers.MessageOpen)
	web.Get("/messages/{url:uuid}/history", middlewares.AuthSubscription, controllers.ConversationHistory)
	web.Get("/messages/{url:uuid}/timeline", middlewares.AuthSubscription, controllers.ConversationTimeline)
	web.Get("/messages/{url:uuid}/search", middlewares.AuthSubscription, controllers.SearchConversation)
	web.Get("/messages/{url:uuid}/search-context", middlewares.AuthSubscription, controllers.ConversationSearchContext)
	web.Post("/messages/{url:uuid}/media/retry", middlewares.AuthSubscription, controllers.RetryConversationMedia)
	web.Get("/messages/{url:uuid}/export", middlewares.AuthSubscription, middlewares.RequireCompanyAdmin, controllers.ExportCurrentConversation)
	web.Get("/messages/{url:uuid}/export/contact", middlewares.AuthSubscription, middlewares.RequireCompanyAdmin, controllers.ExportContactConversations)
	web.Get("/messages/{url:uuid}/notification", middlewares.AuthSubscription, controllers.ConversationNotification)
	web.Post("/messages/{url:uuid}/read", middlewares.AuthSubscription, controllers.MarkConversationRead)
	web.Post("/messages/{url:uuid}/notes", middlewares.AuthSubscription, middlewares.RequireStructuredContentType, controllers.AddConversationNote)
	web.Post("/messages/{url:uuid}/close", middlewares.AuthSubscription, controllers.CloseConversation)
	web.Get("/messages/{url:uuid}/transfer/options", middlewares.AuthSubscription, controllers.ConversationTransferOptions)
	web.Post("/messages/{url:uuid}/transfer", middlewares.AuthSubscription, controllers.TransferConversation)
	web.Post("/messages/{url:uuid}/accept", middlewares.AuthSubscription, controllers.AcceptConversation)
	web.Post("/messages/{url:uuid}/ignore", middlewares.AuthSubscription, controllers.IgnoreConversation)
	web.Post("/messages/{url:uuid}/react", middlewares.AuthSubscription, controllers.ReactToMessage)
	web.Post("/messages/{url:uuid}/edit", middlewares.AuthSubscription, middlewares.RequireStructuredContentType, controllers.EditConversationMessage)
	web.Get("/messages/{url:uuid}/media", middlewares.AuthSubscription, controllers.ListConversationMedia)
	web.Post("/messages/{url:uuid}/media/upload", middlewares.AuthSubscription, controllers.UploadConversationMedia)
	web.Post("/messages/{url:uuid}/media/send", middlewares.AuthSubscription, controllers.SendConversationGalleryMedia)

	web.Get("/departments", controllers.DepartmentSettingsPage)
	web.Get("/agents", controllers.AgentSettingsPage)
	web.Get("/ai-agents", controllers.AIAgentSettingsPage)
	web.Get("/contacts", middlewares.AuthSubscription, controllers.ContactsPage)
	web.Get("/reports", middlewares.AuthSubscription, controllers.ReportsPage)
	web.Get("/quick-replies", controllers.QuickRepliesPage)
	web.Get("/reports/pdf", middlewares.AuthSubscription, controllers.ExportReportPDF)
	web.Get("/media", controllers.MediaLibraryPage)

	flows := web.Party("/flows")
	flows.Use(middlewares.AuthSubscription)
	{
		// HTML page (the visual builder SPA)
		flows.Get("/", controllers.FlowBuilderPage)
		flows.Get("/builder", controllers.FlowBuilderPage)
		flows.Get("/knowledge-base-template.pdf", controllers.DownloadFlowKnowledgeTemplate)

		// JSON API consumed by that page's JS - kept under its own /api
		// sub-path so it never collides with the page route above.
		flowsAPI := flows.Party("/api")
		flowsAPI.Use(middlewares.RequireStructuredContentType)
		{
			flowsAPI.Get("/", controllers.ListFlows)
			flowsAPI.Get("/connections", controllers.ListConnectionsForFlows)
			flowsAPI.Get("/assignment-options", controllers.ListAssignmentOptions)
			flowsAPI.Get("/ai-credentials", controllers.ListFlowAICredentials)
			flowsAPI.Get("/ai-agents", controllers.ListFlowAIAgents)
			flowsAPI.Post("/parse-curl", controllers.ParseFlowCURL)
			flowsAPI.Post("/test-http", controllers.TestFlowHTTPRequest)
			flowsAPI.Post("/media", controllers.UploadFlowMedia)
			flowsAPI.Get("/templates", controllers.ListFlowTemplates)
			flowsAPI.Post("/templates", controllers.CreateFlowTemplate)
			flowsAPI.Put("/templates/{id:int}", controllers.UpdateFlowTemplate)
			flowsAPI.Delete("/templates/{id:int}", controllers.DeleteFlowTemplate)
			flowsAPI.Get("/{id:int}", controllers.GetFlow)
			flowsAPI.Post("/", controllers.CreateFlow)
			flowsAPI.Put("/{id:int}", controllers.UpdateFlow)
			flowsAPI.Delete("/{id:int}", controllers.DeleteFlow)
			flowsAPI.Post("/{id:int}/execute", controllers.ExecuteFlowTest)
		}
	}

	instance := web.Party("/instances")
	instance.Use(middlewares.AuthSubscription, middlewares.RequireCompanyAdmin)
	{
		instance.Get("/", controllers.Instances)
		instance.Get("/list", controllers.InstanceList)
		instance.Get("/events", middlewares.SSEInstances)
		instance.Get("/create", controllers.InstancePopup)
		instance.Post("/create", controllers.NewInstance)
		instance.Post("/{id:int}/reconnect", controllers.AuditCompanyAction("reconnect", "instance", controllers.ReconnectInstance))
		instance.Put("/{id:int}", controllers.AuditCompanyAction("update", "instance", controllers.RenameInstance))
		instance.Delete("/{id:int}", controllers.AuditCompanyAction("delete", "instance", controllers.DeleteInstance))
		instance.Post("/{id:int}/contacts/import", controllers.AuditCompanyAction("import", "contacts", controllers.ImportInstanceContacts))
		instance.Get("/{id:int}/qrcode/events", middlewares.SSEQRCode)
	}

}
